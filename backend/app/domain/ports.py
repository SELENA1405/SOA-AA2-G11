"""Domain ports have no dependencies on other project layers."""
from typing import Protocol

class DataPort(Protocol):
    def health(self) -> bool: ...
    def catalogue(self) -> list[dict]: ...
    def catalogue_item(self, code: str) -> dict | None: ...

class LoadPlanPort(Protocol):
    # Every operation must match BOTH plan code and session code.
    def create_or_get(self, session_code: str) -> tuple[str, bool]: ...   # (plan_code, created)
    def read(self, plan_code: str, session_code: str) -> list[dict]: ...   # [{"equipmentCode","unitCount"}]; raises PlanNotFound
    def add(self, plan_code: str, session_code: str, equipment_code: str, unit_count: int) -> None: ...
    def edit(self, plan_code: str, session_code: str, equipment_code: str, unit_count: int) -> None: ...
    def remove(self, plan_code: str, session_code: str, equipment_code: str) -> None: ...